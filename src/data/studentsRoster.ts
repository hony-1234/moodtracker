export function findStudentByGoogleEmail(email: string): StudentRecord | undefined {
  if (!email) return undefined;
  const cleanEmail = email.toLowerCase().trim();
  const prefix = cleanEmail.split('@')[0].trim();
  
  // Special Testing Account: hony@mail.gccps.edu.hk
  if (cleanEmail === 'hony@mail.gccps.edu.hk') {
    return TESTING_STUDENT_RECORD;
  }

  // 1. Exact email match
  let found = GCCPS_STUDENTS.find(s => s.email && s.email.toLowerCase() === cleanEmail);
  if (found) return found;

  // 2. Student ID / prefix match (e.g. s261002)
  found = GCCPS_STUDENTS.find(s => s.studentId && s.studentId.toLowerCase() === prefix);
  if (found) return found;

  // 3. Fallback contains match
  return GCCPS_STUDENTS.find(s => s.studentId && cleanEmail.includes(s.studentId.toLowerCase()));
}

export function findStudentByClassAndNumber(className: string, number: number | string): StudentRecord | undefined {
  if (!className || number === undefined || number === null || number === '') return undefined;
  if (className.toUpperCase() === 'TEST') {
    const num = typeof number === 'string' ? parseInt(number, 10) || 1 : number || 1;
    return {
      ...TESTING_STUDENT_RECORD,
      number: num
    };
  }
  const targetNum = typeof number === 'string' ? parseInt(number, 10) : number;
  return GCCPS_STUDENTS.find(s => s.class.toUpperCase() === className.toUpperCase() && s.number === targetNum);
}

export function getStudentsByClass(className: string): StudentRecord[] {
  if (!className) return [];
  if (className.toUpperCase() === 'TEST') {
    return [TESTING_STUDENT_RECORD];
  }
  return GCCPS_STUDENTS.filter(s => s.class.toUpperCase() === className.toUpperCase()).sort((a, b) => a.number - b.number);
}

